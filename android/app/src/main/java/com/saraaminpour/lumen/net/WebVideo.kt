package com.saraaminpour.lumen.net

import okhttp3.OkHttpClient
import okhttp3.RequestBody.Companion.toRequestBody
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.downloader.Downloader
import org.schabi.newpipe.extractor.downloader.Request
import org.schabi.newpipe.extractor.downloader.Response
import org.schabi.newpipe.extractor.exceptions.ReCaptchaException
import org.schabi.newpipe.extractor.localization.Localization
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamType
import java.util.concurrent.TimeUnit

/** What mpv needs to play a web page's video: a video URL, an optional separate audio URL, subtitles. */
data class ResolvedVideo(
    val title: String,
    val video: String,
    val audio: String? = null,
    val subtitles: List<Pair<String, String>> = emptyList(),   // url to language label
    val quality: String = "",
    val durationSec: Long = 0,
    val live: Boolean = false,
)

/**
 * Turns YouTube (and the other sites NewPipe understands: SoundCloud, PeerTube, Bandcamp, media.ccc)
 * links into stream URLs. Any other link (direct files, HLS/DASH, …) goes to mpv unchanged.
 */
object WebVideo {
    private val client = OkHttpClient.Builder()
        .readTimeout(30, TimeUnit.SECONDS)
        .connectTimeout(20, TimeUnit.SECONDS)
        .build()
    @Volatile private var ready = false

    private fun init() {
        if (ready) return
        synchronized(this) {
            if (!ready) {
                NewPipe.init(OkDownloader(client), Localization("en", "US"))
                ready = true
            }
        }
    }

    fun isWebPage(url: String): Boolean {
        if (!url.startsWith("http", ignoreCase = true)) return false
        init()
        return try { NewPipe.getServiceByUrl(url) != null } catch (_: Exception) { false }
    }

    /** Blocking: call off the main thread. [maxHeight] 0 = best available. */
    fun resolve(url: String, maxHeight: Int): ResolvedVideo {
        init()
        val info = StreamInfo.getInfo(NewPipe.getServiceByUrl(url), url)
        val live = info.streamType == StreamType.LIVE_STREAM || info.streamType == StreamType.AUDIO_LIVE_STREAM
        if (live && !info.hlsUrl.isNullOrEmpty()) {
            return ResolvedVideo(info.name, info.hlsUrl, live = true, quality = "Live")
        }
        val cap = if (maxHeight > 0) maxHeight else Int.MAX_VALUE
        // video-only streams give the high resolutions; prefer H.264 up to 1080p (hardware decoding
        // everywhere), then VP9, then AV1
        fun codecRank(c: String?): Int = when {
            c == null -> 3
            c.startsWith("avc") -> 0
            c.startsWith("vp9") || c.startsWith("vp09") -> 1
            else -> 2
        }
        val videoOnly = info.videoOnlyStreams
            .filter { it.isUrl && it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && it.height in 1..cap }
            .sortedWith(compareByDescending<org.schabi.newpipe.extractor.stream.VideoStream> { it.height }
                .thenBy { if (it.height <= 1080) codecRank(it.codec) else minOf(codecRank(it.codec), 1) }
                .thenByDescending { it.fps })
        val audio = info.audioStreams
            .filter { it.isUrl && it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP }
            .sortedWith(compareByDescending<org.schabi.newpipe.extractor.stream.AudioStream> {
                // original-language track first when a video has dubbed tracks
                it.audioTrackType?.name == "ORIGINAL" || it.audioTrackType == null
            }.thenByDescending { it.averageBitrate })
            .firstOrNull()
        val muxed = info.videoStreams
            .filter { it.isUrl && it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && it.height <= cap }
            .maxByOrNull { it.height }
        val subs = info.subtitles.filter { it.isUrl && !it.isAutoGenerated }
            .map { it.content to (it.displayLanguageName ?: it.languageTag ?: "Subtitles") }
        val best = videoOnly.firstOrNull()
        return when {
            best != null && audio != null && (muxed == null || best.height > muxed.height) ->
                ResolvedVideo(info.name, best.content, audio.content, subs, "${best.height}p", info.duration)
            muxed != null -> ResolvedVideo(info.name, muxed.content, null, subs, "${muxed.height}p", info.duration)
            audio != null -> ResolvedVideo(info.name, audio.content, null, subs, "Audio", info.duration)
            !info.dashMpdUrl.isNullOrEmpty() -> ResolvedVideo(info.name, info.dashMpdUrl, null, subs, "", info.duration)
            !info.hlsUrl.isNullOrEmpty() -> ResolvedVideo(info.name, info.hlsUrl, null, subs, "", info.duration)
            else -> throw IllegalStateException("No playable stream found")
        }
    }
}

private class OkDownloader(private val client: OkHttpClient) : Downloader() {
    override fun execute(request: Request): Response {
        val body = request.dataToSend()?.toRequestBody()
        val b = okhttp3.Request.Builder()
            .method(request.httpMethod(), body)
            .url(request.url())
            .addHeader("User-Agent", UA)
        request.headers().forEach { (name, values) ->
            b.removeHeader(name)
            values.forEach { b.addHeader(name, it) }
        }
        client.newCall(b.build()).execute().use { r ->
            if (r.code == 429) throw ReCaptchaException("reCaptcha challenge requested", request.url())
            return Response(r.code, r.message, r.headers.toMultimap(), r.body?.string(), r.request.url.toString())
        }
    }

    companion object {
        const val UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:140.0) Gecko/20100101 Firefox/140.0"
    }
}
